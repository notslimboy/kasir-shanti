import { describe, expect, it } from "vitest";
import { existsSync, readFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";

/* PWA identity.
 *
 * There was no manifest at all, so the home-screen icon was whatever the
 * browser guessed from `favicon.png` — a 192px file that gets upscaled to a
 * 512px tile, which turns the wordmark into mush. The app was also still
 * titled "Kasir Shanti — Next".
 *
 * These are the two things that only show up on a phone, so nothing in the
 * desktop suite would catch a regression: the launcher reads the manifest,
 * and iOS reads `apple-touch-icon`. */

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (p: string) => readFileSync(root + p, "utf8");

/* Parsed by hand rather than imported: `resolveJsonModule` types a JSON
   default export as `string` here, which would push every assertion below
   through a cast. Parsing it also means a malformed manifest fails the suite
   instead of silently becoming a string. */
const manifest = JSON.parse(read("public/manifest.webmanifest")) as {
  name: string;
  short_name: string;
  start_url: string;
  scope: string;
  display: string;
  theme_color: string;
  background_color: string;
  icons: { src: string; sizes: string; purpose?: string }[];
};

const html = read("index.html");

const ICON = {
  192: "public/icons/icon-192.png",
  512: "public/icons/icon-512.png",
} as const;

describe("manifest PWA", () => {
  it("namanya 'Shanti Kasir', bukan 'Kasir Shanti — Next'", () => {
    /* `name` is the install prompt and the app switcher; `short_name` is the
       label under the home-screen icon, where anything past about 12
       characters gets truncated. "Shanti Kasir" fits both. */
    expect(manifest.name).toBe("Shanti Kasir");
    expect(manifest.short_name).toBe("Shanti Kasir");
    expect(manifest.name).not.toMatch(/next/i);
    expect(manifest.short_name.length).toBeLessThanOrEqual(12);
  });

  it("short_name cukup pendek untuk label di home screen", () => {
    /* Android ellipsises past ~12 characters depending on launcher density.
       Being marginally over is how an app ends up named "Shanti Kasir C…". */
    expect(manifest.short_name.length).toBeLessThanOrEqual(12);
  });

  it("semua ikon yang disebut benar-benar ada", () => {
    for (const i of manifest.icons) {
      const p = root + "public" + i.src;
      expect(existsSync(p), `${i.src} disebut di manifest tapi tidak ada`).toBe(true);
      expect(statSync(p).size, `${i.src} berukuran nol`).toBeGreaterThan(0);
    }
  });

  it("menyediakan 192 dan 512, minimum yang diminta install prompt", () => {
    const sizes = manifest.icons.map((i) => i.sizes);
    expect(sizes).toContain("192x192");
    expect(sizes).toContain("512x512");
  });

  it("punya ikon maskable, supaya launcher Android tidak memotong logo", () => {
    /* Android crops maskable icons to whatever shape the launcher picks and
       can eat up to 20% off every edge. Without a maskable entry it just
       scales the transparent-bordered one and the logo gets clipped. */
    const maskable = manifest.icons.filter((i) => i.purpose === "maskable");
    expect(maskable.length).toBeGreaterThanOrEqual(2);
    for (const i of maskable) {
      expect(i.sizes).toMatch(/^(192|512)x192|512x512$/);
    }
  });

  it("ikon 512 ada, bukan cuma upscale dari 192", () => {
    /* The original artwork is 192x192. A 512 icon generated by upscaling that
       is visibly soft on a home screen, so the two sizes must exist as real
       files rather than one file referenced twice. */
    expect(ICON[192]).not.toBe(ICON[512]);
    expect(existsSync(root + ICON[512])).toBe(true);
  });

  it("start_url dan scope ke root", () => {
    /* Deep-linking into /kasir directly would open the app outside its scope
       on some launchers, which then refuses to open it at all. */
    expect(manifest.start_url).toBe("/");
    expect(manifest.scope).toBe("/");
  });

  it("warna tema konsisten dengan krem logo", () => {
    /* Sampled from the logo disc in public/favicon.png: (250, 242, 222). A
       mismatch shows as a differently coloured status bar beside the icon,
       which is the kind of detail that makes a shop's app look unofficial. */
    const cream = "#faf2de";
    expect(manifest.theme_color).toBe(cream);
    expect(manifest.background_color).toBe(cream);
  });

  it("display standalone, supaya terbuka tanpa address bar", () => {
    expect(manifest.display).toBe("standalone");
  });
});

describe("index.html", () => {
  it("title-nya 'Shanti Kasir'", () => {
    expect(html).toContain("<title>Shanti Kasir</title>");
    expect(html).not.toMatch(/Kasir Shanti — Next/);
  });

  it("menautkan manifest", () => {
    /* Without the link tag the manifest is never read and the install prompt
       never appears, no matter how correct the file is. */
    expect(html).toMatch(/<link[^>]+rel="manifest"[^>]+href="\/manifest\.webmanifest"/);
  });

  it("menyertakan apple-touch-icon, karena iOS mengabaikan favicon", () => {
    expect(html).toMatch(/<link[^>]+rel="apple-touch-icon"/);
    expect(html).toContain('/icons/icon-180.png');
    expect(existsSync(root + "public/icons/icon-180.png")).toBe(true);
  });

  it("menyertakan theme-color", () => {
    expect(html).toMatch(/<meta[^>]+name="theme-color"/);
  });

  it("nama untuk iOS juga 'Shanti Kasir'", () => {
    /* iOS reads apple-mobile-web-app-title, not `name`, for the home-screen
       label — and it falls back to the document title if the meta is absent,
       which is how a "Next" suffix ends up on a customer's phone. */
    expect(html).toMatch(/name="apple-mobile-web-app-title"[^>]+content="Shanti Kasir"/);
  });
});